// Optional, reproducible frontend preparation. Cargo never downloads viewer assets.
import {build} from '../web/node_modules/esbuild/lib/main.js';
import {readFile,writeFile,mkdir,copyFile,readdir,rm} from 'node:fs/promises';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('..',import.meta.url)));
const assetRoot='web/model-viewer-assets';
await rm(assetRoot,{recursive:true,force:true});
const assets={
  'occt-import-js':['dist/occt-import-js-worker.js','dist/occt-import-js.js','dist/occt-import-js.wasm','dist/license.occt-import-js.txt','dist/license.occt.txt'],
  rhino3dm:['rhino3dm.min.js','rhino3dm.wasm'],
  'web-ifc':['web-ifc-api-iife.js','web-ifc.wasm','web-ifc-mt.wasm','web-ifc-mt.worker.js'],
  draco3d:['draco_decoder_nodejs.js','draco_decoder.wasm'],
};
for(const [pkg,files]of Object.entries(assets)){
  await mkdir(`${assetRoot}/${pkg}`,{recursive:true});
  for(const file of files)await copyFile(`web/node_modules/${pkg}/${file}`,`${assetRoot}/${pkg}/${file.split('/').at(-1)}`);
}
await mkdir(`${assetRoot}/environment`,{recursive:true});
for(const face of ['posx','negx','posy','negy','posz','negz','readme']){
  const name=face==='readme'?'readme.txt':face+'.jpg';
  await copyFile(`web/node_modules/online-3d-viewer/website/assets/envmaps/fishermans_bastion/${name}`,`${assetRoot}/environment/${name}`);
}
// Surface rejected importer promises as a failed import instead of leaving the UI loading.
const workerPath=`${assetRoot}/occt-import-js/occt-import-js-worker.js`;
await writeFile(workerPath,(await readFile(workerPath,'utf8'))+`\n// Agentworks: report asynchronous importer failures.\nself.addEventListener('unhandledrejection',event=>{event.preventDefault();self.postMessage({success:false});});\n`);
const result=await build({entryPoints:['web/model-viewer-frame.entry.js'],bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'eof',metafile:true,outfile:'web/model-viewer-frame.bundle.js',plugins:[{
  name:'local-model-importers',setup(build){
    build.onResolve({filter:/^online-3d-viewer$/},()=>({path:resolve('web/node_modules/online-3d-viewer/source/engine/main.js')}));
    build.onLoad({filter:/importerutils\.js$/},async({path})=>{
      let contents=await readFile(path,'utf8'),count=0;
      contents=contents.replace(/'https:\/\/cdn\.jsdelivr\.net\/npm\/([^@]+)@[^/]+\/([^']*)'/g,(_,pkg,file)=>{
        count++;file=file.replace(/^dist\//,'').replace('draco_decoder_nodejs.min.js','draco_decoder_nodejs.js');
        return `new URL('./model-viewer-assets/${pkg}/${file}',document.baseURI).href`;
      });
      if(count!==4)throw new Error('Viewer importer URLs changed; update the local asset mapping.');
      return {contents,loader:'js'};
    });
  },
}]});
const packages=new Map();
for(const input of Object.keys(result.metafile.inputs)){
  if(!input.includes('node_modules/'))continue;
  let dir=dirname(resolve(input));
  while(dir!==dirname(dir)){
    try{const pkg=JSON.parse(await readFile(join(dir,'package.json'),'utf8'));if(pkg.name){packages.set(dir,pkg);break;}}catch{}
    dir=dirname(dir);
  }
}
for(const pkg of Object.keys(assets)){const dir=resolve('web/node_modules',pkg);packages.set(dir,JSON.parse(await readFile(join(dir,'package.json'),'utf8')));}
let notices='Online 3D Viewer — third-party notices\nGenerated by npm run build:model-viewer\n';
for(const [dir,pkg]of [...packages].sort((a,b)=>a[1].name.localeCompare(b[1].name))){
  notices+=`\n\n=== ${pkg.name} ${pkg.version} (${pkg.license||'see package source'}) ===\nSource: ${typeof pkg.repository==='string'?pkg.repository:pkg.repository?.url||pkg.homepage||''}\n`;
  for(const name of (await readdir(dir)).filter(name=>/^(?:licen[sc]e|copying|notice)(?:\.|$)/i.test(name)))notices+=await readFile(join(dir,name),'utf8');
}
for(const name of (await readdir('web/vendor/model-viewer')).filter(name=>name.endsWith('-LICENSE.txt')))notices+='\n\n'+name+'\n'+await readFile('web/vendor/model-viewer/'+name,'utf8');
notices+='\n\nEnvironment map: Fishermans Bastion\n'+await readFile(`${assetRoot}/environment/readme.txt`,'utf8');
await writeFile(`${assetRoot}/LICENSES.txt`,notices);
console.log('Built optional model viewer and local CAD importers. Build Cargo with --features model-viewer.');
