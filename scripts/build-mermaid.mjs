import {build} from '../web/node_modules/esbuild/lib/main.js';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {dirname,resolve,join} from 'node:path';
const result=await build({entryPoints:['web/mermaid-frame.entry.js'],bundle:true,format:'iife',platform:'browser',
  target:'es2022',minify:true,legalComments:'eof',metafile:true,outfile:'web/mermaid-frame.bundle.js'});
const packages=new Map();
for(const input of Object.keys(result.metafile.inputs)){
  if(!input.includes('node_modules/'))continue;
  let dir=dirname(resolve(input));
  while(dir!==dirname(dir)){
    try{const pkg=JSON.parse(await readFile(join(dir,'package.json'),'utf8'));
      if(pkg.name){packages.set(dir,pkg);break;}
    }catch{}
    dir=dirname(dir);
  }
}
let notices='Bundled Mermaid renderer — third-party license notices\nGenerated by node scripts/build-mermaid.mjs\n';
for(const [dir,pkg]of [...packages].sort((a,b)=>a[1].name.localeCompare(b[1].name))){
  notices+=`\n\n=== ${pkg.name} ${pkg.version} (${pkg.license||'see below'}) ===\n`;
  for(const name of (await readdir(dir)).filter(name=>/^(?:licen[sc]e|copying|notice)(?:\.|$)/i.test(name))){
    try{notices+=await readFile(join(dir,name),'utf8');}catch{}
  }
}
await writeFile('web/mermaid-LICENSES.txt',notices);
