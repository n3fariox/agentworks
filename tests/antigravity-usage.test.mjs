import assert from 'node:assert/strict';
import {emptyUsage,applyUsageEvent,sharedQuota,withSharedQuota,usageView,STALE_MS} from '../web/usage-status.js';
import {usageMeters} from '../web/dashboard.js';
const at=Date.parse('2026-11-11T15:00:00Z');
const report={observedAtMs:at,windows:[{id:'gemini-5h',group:'Gemini Models',window:'5h',remainingFraction:0.75,resetTime:'2026-11-11T19:00:00Z'}, {id:'argon-weekly',group:'Argon',window:'weekly',remainingFraction:0.2,resetTime:null}]};
const event={kind:'antigravity_quota',data:report};
const state=applyUsageEvent(emptyUsage(),event);
assert.equal(state.context,null,'Quota must not manufacture context occupancy');
let view=usageView(state,{now:at,provider:'antigravity'});
assert(view.details.some(s=>s.includes('Gemini Models · 5h: 75% left')));
assert.match(view.label,/Argon · weekly 20% left/);
assert.equal(view.known,true);assert.equal(view.stale,false);
assert.match(view.short,/Argon · weekly 20% left/);
assert(view.details.some(s=>s.includes('resets in 4h')));
assert(view.details.some(s=>s.includes('reset unknown')));
assert(!view.details.some(s=>s.includes('7d quota')));
assert(usageView(state,{now:at+STALE_MS+1,provider:'antigravity'}).label.includes('⚠'));
assert.equal(applyUsageEvent(state,{...event,data:{...report,observedAtMs:at-1}}),state);
const shared=sharedQuota({antigravity:{...report,observedAtMs:at+1}});
assert.equal(withSharedQuota(state,shared).antigravityQuota.observedAtMs,at+1);
assert.equal(withSharedQuota(shared,state).antigravityQuota.observedAtMs,at+1);
assert.equal(usageMeters(state,at)[0].percent,25);
assert.equal(usageMeters(state,at)[1].percent,80);
const invalid=applyUsageEvent(emptyUsage(),{kind:'antigravity_quota',data:{observedAtMs:at,windows:[{id:'bad',group:'Bad',remainingFraction:2,resetTime:'invalid'}]}});
assert.match(usageView(invalid,{now:at,provider:'antigravity'}).label,/quota unknown/);
assert.equal(usageMeters(invalid,at).length,0);
console.log('PASS: Antigravity quota rendering, reset times, staleness, replay ordering and dashboard meters');
