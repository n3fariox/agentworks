//! The form produces an ordinary, self-contained script. The script remains
//! canonical after saving; the definition is its control/authority index.
use super::scripts::{self, ScriptTrigger, Settings};
use super::*;
use axum::extract::{Path, State};
use serde_json::Value;

#[derive(Clone, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct Form {
    host: String,
    repo: String,
    account: String,
    #[serde(default = "enabled")]
    assigned: bool,
    #[serde(default = "enabled")]
    review_requested: bool,
    #[serde(default)]
    include_existing: bool,
    settings: Settings,
    steps: Vec<Step>,
}
/// JSON string escaping is valid for Starlark strings. Values are encoded
/// recursively, so tokens inside strings are never rewritten as code.
pub(super) fn literal(value: &Value) -> String {
    match value {
        Value::Null => "None".into(),
        Value::Bool(true) => "True".into(),
        Value::Bool(false) => "False".into(),
        Value::Array(v) => format!("[{}]", v.iter().map(literal).collect::<Vec<_>>().join(", ")),
        Value::Object(v) => format!(
            "{{{}}}",
            v.iter()
                .map(|(k, v)| format!("{}: {}", json!(k), literal(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        _ => value.to_string(),
    }
}
pub(super) fn generate(form: &Form) -> Result<String, String> {
    let (_, prompt) = Workflow {
        version: 1,
        trigger: Trigger::Manual,
        steps: form.steps.clone(),
    }
    .compile()
    .map_err(str::to_owned)?;
    let texts: Vec<_> = form
        .steps
        .iter()
        .map(|Step::Agent { text }| text.trim())
        .collect();
    let mut scope = GithubReview {
        host: form.host.clone(),
        owner: form
            .repo
            .split_once('/')
            .ok_or("Use repository as owner/repo")?
            .0
            .into(),
        repo: form.repo.split_once('/').unwrap().1.into(),
        login: form.account.clone(),
        assigned: form.assigned,
        review_requested: form.review_requested,
        include_existing: form.include_existing,
    };
    scope.validate().map_err(str::to_owned)?;
    if form.settings.project_id.is_empty() {
        return Err("Choose a review project".into());
    }
    let mut source = agentworks_starlark::GITHUB_REVIEW_SCRIPT
        .replace("\"parameter\", ", "\"instruction_steps\", ");
    source=source.replacen("\n\n",&format!("\n\n# Generated by the automation form. This file owns the configuration and policy.\nSETTINGS = {}\nSTEPS = {}\n\n",literal(&json!(form.settings)),literal(&json!(texts))),1);
    source = source
        .replace("parameter(\"host\")", &literal(&json!(scope.host)))
        .replace(
            "parameter(\"repo\")",
            &literal(&json!(format!("{}/{}", scope.owner, scope.repo))),
        )
        .replace("parameter(\"account\")", &literal(&json!(scope.login)));
    let events: Vec<_> = [
        (form.assigned, "pr.assigned_to_me"),
        (form.review_requested, "pr.review_requested"),
    ]
    .into_iter()
    .filter_map(|(selected, event)| selected.then_some(event))
    .collect();
    source=source.replace("events = [\"pr.assigned_to_me\", \"pr.review_requested\"],",&format!("events = {},\n    include_existing = {},\n    settings = SETTINGS,\n    instructions = instruction_steps(STEPS),\n    steps = STEPS,",literal(&json!(events)),literal(&json!(form.include_existing))));
    // Keep the compiler and generator's instruction semantics in agreement.
    if prompt.is_empty() {
        return Err("Add review instructions".into());
    }
    Ok(source)
}
pub async fn preview(State(app): State<App>, Json(form): Json<Form>) -> ApiResult {
    let source = generate(&form).map_err(|e| fail(StatusCode::BAD_REQUEST, e))?;
    scripts::resolve_source(&app.progress.engine(), &binding("preview.star"), &source)
        .map_err(|e| fail(StatusCode::BAD_REQUEST, e))?;
    Ok(Json(json!({"source":source})))
}
pub(super) fn binding(name: &str) -> ScriptTrigger {
    ScriptTrigger {
        script: name.into(),
        handler: "default".into(),
        parameters: Default::default(),
    }
}
pub(super) fn descriptor(
    app: &App,
    name: &str,
    source: &str,
) -> Result<Value, (StatusCode, String)> {
    let (descriptor, _) = scripts::manifest(&app.progress.engine(), name, source)
        .map_err(|e| fail(StatusCode::BAD_REQUEST, e))?;
    if !descriptor["settings"].is_object()
        || !descriptor["instructions"]
            .as_str()
            .is_some_and(|s| !s.trim().is_empty())
    {
        return Err(fail(
            StatusCode::BAD_REQUEST,
            "The script must register its settings and instructions",
        ));
    }
    Ok(descriptor)
}
pub async fn get(State(app): State<App>, Path(id): Path<String>) -> ApiResult {
    let def = existing(&app, &id)?;
    let bound = scripts::binding(&def)
        .ok_or_else(|| fail(StatusCode::BAD_REQUEST, "This automation has no script"))?;
    let source: String = app
        .store
        .lock()
        .unwrap()
        .connection
        .query_row(
            "SELECT source FROM scripts WHERE name=?1",
            [&bound.script],
            |r| r.get(0),
        )
        .map_err(storage)?;
    let descriptor = match descriptor(&app, &bound.script, &source) {
        Ok(d) => d,
        Err((_, error)) => {
            return Ok(Json(
                json!({"name":bound.script,"source":source,"form":null,"generated":false,"error":error}),
            ));
        }
    };
    let form = from_descriptor(&descriptor)?;
    let generated = generate(&form).is_ok_and(|s| s == source);
    Ok(Json(
        json!({"name":bound.script,"source":source,"form":form_view(&form),"generated":generated}),
    ))
}
pub(super) fn steps(d: &Value) -> Vec<Step> {
    let instructions = d["instructions"].as_str().unwrap_or_default();
    let mut steps: Vec<Step> = d["steps"]
        .as_array()
        .map(|v| {
            v.iter()
                .filter_map(|s| s.as_str())
                .map(|text| Step::Agent { text: text.into() })
                .collect()
        })
        .unwrap_or_default();
    if !(Workflow {
        version: 1,
        trigger: Trigger::Manual,
        steps: steps.clone(),
    })
    .compile()
    .is_ok_and(|(_, p)| p == instructions)
    {
        steps = vec![Step::Agent {
            text: instructions.into(),
        }];
    }
    steps
}
fn from_descriptor(d: &Value) -> Result<Form, (StatusCode, String)> {
    let steps = steps(d);
    serde_json::from_value(json!({"host":d["host"],"repo":d["repo"],"account":d["account"],"assigned":d["events"].as_array().is_some_and(|e|e.contains(&json!("pr.assigned_to_me"))),"reviewRequested":d["events"].as_array().is_some_and(|e|e.contains(&json!("pr.review_requested"))),"includeExisting":d["includeExisting"],"settings":d["settings"],"steps":steps})).map_err(|e|fail(StatusCode::BAD_REQUEST,format!("Invalid script configuration: {e}")))
}
fn form_view(form: &Form) -> Value {
    json!({"host":form.host,"repo":form.repo,"account":form.account,"assigned":form.assigned,"reviewRequested":form.review_requested,"includeExisting":form.include_existing,"settings":form.settings,"steps":form.steps})
}

pub(super) fn apply(
    app: &App,
    name: &str,
    input: &mut Input,
    source: &str,
) -> Result<(), (StatusCode, String)> {
    let descriptor = descriptor(app, &name, source)?;
    let form = from_descriptor(&descriptor)?;
    input.name = form
        .settings
        .title
        .clone()
        .filter(|s| !s.trim().is_empty())
        .unwrap_or_else(|| name.trim_end_matches(".star").into());
    input.provider = form.settings.provider;
    input.cwd = form.settings.cwd;
    input.model = form.settings.model;
    input.model_provider = form.settings.model_provider;
    input.project_id = Some(form.settings.project_id);
    input.host_id = Some(form.settings.host_id);
    input.prompt = descriptor["instructions"].as_str().unwrap().into();
    input.workflow = Some(Workflow {
        version: 1,
        trigger: Trigger::Script(super::scripts::ScriptTrigger {
            handler: descriptor["name"].as_str().unwrap().into(),
            ..binding(&name)
        }),
        steps: form.steps,
    });
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn form(cwd: &str) -> Form {
        serde_json::from_value(json!({"host":"github.com","repo":"team/repo","account":"fixture","assigned":false,"reviewRequested":true,"settings":{"provider":"demo","cwd":cwd,"projectId":"p","hostId":"local","title":"Quotes \" None True False"},"steps":[{"kind":"agent","text":"Read \"quoted\" values and None True False.\nKeep \\ paths."},{"kind":"agent","text":"Report findings."}]})).unwrap()
    }
    #[test]
    fn generated_file_is_self_contained_and_round_trips_without_rewriting_strings() {
        let form = form("/tmp/repo");
        let source = generate(&form).unwrap();
        assert!(!source.contains("parameter("));
        let engine = agentworks_starlark::engine::Engine::new().unwrap();
        let recipe = scripts::resolve_source(&engine, &binding("file.star"), &source).unwrap();
        let descriptor = recipe.script.automation_trigger.as_ref().unwrap();
        assert_eq!(descriptor["settings"]["title"], json!(form.settings.title));
        assert_eq!(descriptor["settings"]["model"], Value::Null);
        let (_, expected) = Workflow {
            version: 1,
            trigger: Trigger::Manual,
            steps: form.steps.clone(),
        }
        .compile()
        .unwrap();
        assert_eq!(descriptor["instructions"], expected);
        let restored = from_descriptor(descriptor).unwrap();
        assert_eq!(generate(&restored).unwrap(), source);
        assert!(!recipe.scope.assigned && recipe.scope.review_requested);
    }
    #[tokio::test]
    async fn source_and_execution_index_save_atomically_and_custom_source_is_preserved() {
        let f = crate::github_tracking::tests::Fixture::new().await;
        f.app
            .catalog
            .lock()
            .unwrap()
            .data
            .projects
            .push(serde_json::from_value(json!({"id":"p","name":"Reviews"})).unwrap());
        let source = generate(&form(&f.s.cwd.to_string_lossy())).unwrap();
        let builtin = f
            .app
            .store
            .lock()
            .unwrap()
            .connection
            .query_row(
                "SELECT source FROM scripts WHERE name='bazel_progress.star'",
                [],
                |r| r.get::<_, String>(0),
            )
            .unwrap();
        let input=serde_json::from_value(json!({"name":"Generated review","source":source,"provider":"ignored","cwd":"/ignored","enabled":false})).unwrap();
        let Json(saved) = crate::automations::create(State(f.app.clone()), Json(input))
            .await
            .unwrap();
        assert_eq!(saved["provider"], "demo");
        assert_eq!(saved["cwd"], f.s.cwd.to_string_lossy().as_ref());
        assert_eq!(saved["projectId"], "p");
        let id = saved["id"].as_str().unwrap();
        let Json(file) = get(State(f.app.clone()), Path(id.into())).await.unwrap();
        assert_eq!(file["source"], source);
        assert_eq!(file["generated"], true);
        assert_eq!(file["name"], format!("automation_{id}.star"));
        assert_eq!(file["form"]["steps"].as_array().unwrap().len(), 2);
        let custom = format!("{source}\n# custom policy, preserved verbatim\n");
        let input = serde_json::from_value(
            json!({"name":"Generated review","source":custom,"enabled":false}),
        )
        .unwrap();
        let _ = crate::automations::update(State(f.app.clone()), Path(id.into()), Json(input))
            .await
            .unwrap();
        let Json(file) = get(State(f.app.clone()), Path(id.into())).await.unwrap();
        assert_eq!(file["source"], custom);
        assert_eq!(file["generated"], false);
        assert_eq!(
            f.app
                .store
                .lock()
                .unwrap()
                .connection
                .query_row(
                    "SELECT source FROM scripts WHERE name='bazel_progress.star'",
                    [],
                    |r| r.get::<_, String>(0)
                )
                .unwrap(),
            builtin
        );
        let count: i64 = f
            .app
            .store
            .lock()
            .unwrap()
            .connection
            .query_row("SELECT count(*) FROM scripts", [], |r| r.get(0))
            .unwrap();
        f.app.store.lock().unwrap().connection.execute_batch("CREATE TRIGGER reject_generated BEFORE INSERT ON automations BEGIN SELECT RAISE(ABORT,'fixture storage failure'); END;").unwrap();
        let input = serde_json::from_value(
            json!({"name":"Must roll back","source":source,"enabled":false}),
        )
        .unwrap();
        assert!(
            crate::automations::create(State(f.app.clone()), Json(input))
                .await
                .is_err()
        );
        assert_eq!(
            f.app
                .store
                .lock()
                .unwrap()
                .connection
                .query_row("SELECT count(*) FROM scripts", [], |r| r.get::<_, i64>(0))
                .unwrap(),
            count
        );
    }
}

#[derive(Deserialize)]
pub struct Inspect {
    name: Option<String>,
    source: String,
}
pub async fn inspect(State(app): State<App>, Json(input): Json<Inspect>) -> ApiResult {
    let name = input.name.unwrap_or_else(|| "import.star".into());
    if !crate::tool_progress::valid_name(&name) {
        return Err(fail(
            StatusCode::BAD_REQUEST,
            "Use a lowercase .star filename",
        ));
    }
    let descriptor = descriptor(&app, &name, &input.source)?;
    let form = from_descriptor(&descriptor)?;
    Ok(Json(
        json!({"name":name,"source":input.source,"form":form_view(&form),"generated":false}),
    ))
}
